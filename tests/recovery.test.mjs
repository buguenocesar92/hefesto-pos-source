import assert from 'node:assert/strict';
import {seed,act,expected} from '../lib/pos.ts';
import {parseRecovery,serializeRecovery,recoveredOutcome} from '../lib/recovery.ts';
const s=seed(),id=s.products[0].id;
const call=a=>act(s,{requestId:crypto.randomUUID(),...a});
call({type:'open',opening:10000});
const action={type:'sale',lines:[{id,qty:.3}],method:'cash',received:477};
const pending={key:JSON.stringify(action),id:crypto.randomUUID(),version:1};
const draft={cart:action.lines,customer:'',discount:0,holdId:''};
const saved=parseRecovery(serializeRecovery(draft,pending));
assert.deepEqual(saved,{draft,pending});
assert.equal(recoveredOutcome(s.processed,pending),false);
call({...action,requestId:saved.pending.id});
const afterSale=structuredClone(s);
assert.equal(recoveredOutcome(s.processed,saved.pending),true);
call({...JSON.parse(saved.pending.key),requestId:saved.pending.id});
assert.deepEqual(s,afterSale,'Recovered request cannot duplicate sale or stock movement');
call({type:'void',id:s.sales[0].id,reason:'Fracción anulada'});
assert.equal(s.products[0].stock,48);
call({type:'sale',lines:[{id,qty:2}],method:'cash',received:3180});
const sale=s.sales.at(-1),cash=expected(s,s.sessions[0]);
call({type:'return',sale:sale.id,reason:'Envase roto',disposition:'damaged',method:'cash',lines:[{product:id,qty:1}]});
assert.equal(s.products[0].stock,46);
assert.equal(expected(s,s.sessions[0]),cash-1590);
assert.equal(s.returns.at(-1).disposition,'damaged');
assert.equal(s.movements.at(-1).qty,0);
call({type:'return',sale:sale.id,reason:'Sellado intacto',disposition:'restock',method:'cash',lines:[{product:id,qty:1}]});
assert.equal(s.products[0].stock,47);
const snapshot=structuredClone(s);
assert.throws(()=>call({type:'close',counted:-1}),/Importe/);
assert.deepEqual(s,snapshot,'Rejected action must not partially mutate its caller');
assert.throws(()=>call({type:'cash',amount:10,direction:'invalid',reason:'Test'}),/Dirección/);
assert.deepEqual(s,snapshot);
assert.throws(()=>call({type:'product',product:{...s.products[1],id:undefined,sku:' '+s.products[0].sku+' ',barcode:''}}),/duplicado/);
assert.equal(parseRecovery(null),null);
assert.throws(()=>parseRecovery('{bad'));
assert.throws(()=>parseRecovery(serializeRecovery(draft,{...pending,version:-1})));
console.log('PASS: persisted retry, exact-once sale, atomic rejection, fractional void, damaged/restocked returns, duplicate normalized SKU, invalid recovery.');
